-- ============================================================
-- 문항별 힌트 재료
-- 적용: npm run db:schema   (멱등)
--
-- 왜 필요한가: 지금 힌트는 **전략**만 준다 — "동사를 명사로 바꾸세요".
-- 그런데 한국 학생이 실제로 막히는 자리는 그 앞이다.
--   ① 이 표현이 무슨 뜻인지 모른다        → 전략을 알아도 쓸 것이 없다
--   ② 뜻은 아는데 영어 낱말이 안 떠오른다  → 인출 실패이지 이해 실패가 아니다
--   ③ vary 의 명사형이 variability 인 줄 모른다 → 어형 지식이지 패러프레이즈 능력이 아니다
-- 셋 다 "혼자 만들어 내라" 로는 넘을 수 없고, 자습이라 물어볼 사람도 없다.
--
-- 이 재료를 **미리 만들어 둔다.** 요청할 때마다 LLM 을 부르면 문항 하나에 돈이
-- 반복해서 들고 느리다. 힌트는 문항마다 고정이므로 한 번 만들면 끝이다
-- (판정 캐시가 일관성을 위해 존재하는 것과 같은 이유로, 여기서도 **같은 문항에
--  항상 같은 힌트**가 나와야 학생이 앱을 믿는다).
--
-- 저장 형태 (JSON):
--   {
--     "gloss":  "능숙한 전문가들",              -- 1칸: 대상의 한국어 뜻
--     "shape":  "b______ (2낱말)",              -- 2칸: 유형1 인출 발판
--     "form":   "vary → variability",           -- 2칸: 유형2 어형
--     "example":"highly skilled workers"        -- 3칸: 예시 답 하나
--   }
-- 유형에 따라 쓰이는 열쇠가 다르다. 없는 열쇠는 그 칸을 건너뛴다.
-- ============================================================

ALTER TABLE pc_tasks ADD COLUMN hints TEXT;
