// ============================================================
// 지시문·힌트의 강조를 그린다.
//
// 지시문(render.ts PROMPTS)과 힌트(hint.ts)는 처음부터 `**…**` 로 강조를 적어
// 왔는데, 화면은 그것을 **문자 그대로** 뿌리고 있었다. 학생 화면에
// `밑줄 친 부분을 **같은 뜻의 다른 말로** 다시 쓰세요.` 가 별표째 나간다.
//
// 문구를 고쳐 별표를 지우는 방법도 있지만, 그러면 강조가 사라진다 —
// 저 강조는 "이 유형이 요구하는 조작"을 가리키는 자리라 굵게 보이는 편이 낫다.
//
// 마크다운 파서를 넣지 않는다. 여기서 쓰는 문법은 `**` 하나뿐이고,
// 라이브러리를 들이면 학생 답안·지문까지 해석하게 되어 사고 면적만 넓어진다.
// ============================================================

import { Fragment } from "react"

/** `**강조**` 만 굵게. 짝이 안 맞는 별표는 그냥 글자로 남는다. */
export function Emphasis({ text }: { text: string }) {
  const parts = text.split("**")
  return (
    <>
      {parts.map((part, i) =>
        // 홀수 번째 조각이 별표 사이에 있던 것이다.
        i % 2 === 1 ? <b key={i}>{part}</b> : <Fragment key={i}>{part}</Fragment>,
      )}
    </>
  )
}
